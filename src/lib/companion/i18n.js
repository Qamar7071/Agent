export const LANGS = { en: 'English', ur: 'Roman Urdu' };

export function strings(lang) {
  return STR[lang] || STR.en;
}

/** The rule-based sentence for a nudge, in the chosen language. */
export function nudgeText(nudge, lang, name) {
  const s = strings(lang);
  const catName = nudge.facts?.category ? s.cat[nudge.facts.category] : '';
  return s.nudge[nudge.ruleId]?.(nudge.facts, nudge.ruleId === 'R4' ? null : name, catName) || '';
}

export function optionLabel(option, lang) {
  const s = strings(lang);
  if (option.kind === 'stay_down' || option.kind === 'bus') return s.opt[option.kind](option.estSavingPkr);
  if (option.kind === 'cap') return s.opt.cap(option.perDayTarget, s.cat[option.category]);
  return s.opt[option.kind] || option.kind;
}

export function optionSource(option, lang) {
  const s = strings(lang);
  if (option.kind === 'stay_down' || option.kind === 'bus') return `${s.estimate}, ${option.scaled ? s.sourceCostScaled : s.sourceCost}`;
  if (option.kind === 'cap') return s.sourceBudget;
  return null;
}
